export function getMermaidThemeKey() {
  return document.documentElement.getAttribute("data-theme") === "light" ? "light" : "dark";
}

export function applyMermaidTheme() {
  const isLight = getMermaidThemeKey() === "light";
  return {
    startOnLoad: false,
    theme: "base",
    themeVariables: isLight ? SCALE_LIGHT : SCALE_DARK,
    securityLevel: "loose",
    fontFamily: "inherit",
    mindmap: { padding: 14, useMaxWidth: true },
    flowchart: {
      useMaxWidth: true,
      htmlLabels: true,
      curve: "basis",
      padding: 18,
      nodeSpacing: 48,
      rankSpacing: 56,
    },
    sequence: { useMaxWidth: true, wrap: true, mirrorActors: false },
    state: { useMaxWidth: true },
    gantt: { useMaxWidth: true },
  };
}
